"""Render backend/src/memoria/chain_prompts.py as prompts/chain_prompts.md for reading.

The .py file is the source of truth. Re-run after editing it:
    python3 scripts/render_prompts_md.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend" / "src" / "memoria"))
import chain_prompts as c  # noqa: E402

OUT = ROOT / "prompts" / "chain_prompts.md"


def stage_part(system_prompt: str) -> str:
    """Strip the shared MEMORIA_CORE prefix; it is printed once at the top."""
    return system_prompt.removeprefix(c.MEMORIA_CORE).strip()


def type_label(node: dict) -> str:
    t = node.get("type")
    types = t if isinstance(t, list) else [t]
    nullable = "null" in types
    base = next((x for x in types if x != "null"), "any")
    if "enum" in node:
        values = [v for v in node["enum"] if v is not None]
        base = "enum: " + " \\| ".join(f"`{v}`" for v in values)
    elif base == "array":
        item = node["items"]
        inner = "object" if item.get("type") == "object" else type_label(item)
        base = f"array of {inner}"
    return base + (" (nullable)" if nullable else "")


def schema_rows(node: dict, path: str = "") -> list[str]:
    rows = []
    if node.get("type") == "object":
        for key, child in node["properties"].items():
            rows += schema_rows(child, f"{path}.{key}" if path else key)
        return rows
    desc = node.get("description", "").replace("|", "\\|")
    rows.append(f"| `{path}` | {type_label(node)} | {desc} |")
    if node.get("type") == "array" and node["items"].get("type") == "object":
        rows += schema_rows(node["items"], path + "[]")
    return rows


def schema_table(schema: dict) -> str:
    return "\n".join(["| Field | Type | Description |", "|---|---|---|", *schema_rows(schema)])


def block(text: str, lang: str = "text") -> str:
    return f"```{lang}\n{text.strip()}\n```"


def settings_line(stage: dict) -> str:
    keys = ["lane", "runtime", "max_tokens", "effort", "stream", "tools", "max_tool_calls",
            "parallel_per", "on_fail", "max_revisions", "memory_access", "depends_on"]
    parts = []
    for k in keys:
        if k in stage:
            v = stage[k]
            if isinstance(v, dict):
                v = ", ".join(f"{a} {b}" for a, b in v.items())
            elif isinstance(v, list):
                v = ", ".join(v)
            parts.append(f"**{k}:** {v}")
    return " · ".join(parts)


TITLES = {
    "interviewer": "1a — Interviewer (voice)",
    "slot_extractor": "1b — Slot extractor",
    "deal_brief": "2 — Deal Brief",
    "retrieval": "3 — Retrieval",
    "research": "4 — Deep research",
    "personas": "5 — Target personas",
    "strategy": "6 — Campaign strategy",
    "assets": "7 — Asset generators",
    "verifier": "8 — Verifier",
    "memory_writer": "9 — Memory writer",
    "strategy_answer": "10 — Strategy answer (Card D test question)",
}


def render() -> str:
    out = [
        "# Memoria — Chain Prompts",
        "",
        "> Generated from [`chain_prompts.py`](../backend/src/memoria/chain_prompts.py) by `scripts/render_prompts_md.py`. "
        "Edit the `.py`, then regenerate. Do not edit this file by hand.",
        "",
        f"**Model:** `{c.MODEL}` for every stage.",
        "",
        "**How a call is assembled:** shared core → stage prompt (together, the system prompt) → "
        "tenant profile block (stable per tenant, cached) → user template (volatile, filled per call). "
        "Placeholders look like `$name`.",
        "",
        "## Contents",
        "",
        "- [Shared core](#shared-core)",
        "- [Tenant block](#tenant-block)",
    ]
    for stage in c.CHAIN:
        title = TITLES[stage["id"]]
        anchor = title.lower().replace(" ", "-").replace("—", "").replace("(", "").replace(")", "")
        out.append(f"- [{title}](#{anchor})")
    out += ["- [8b — Reviser](#8b--reviser)", "- [Eval prompts](#eval-prompts)", ""]

    out += ["## Shared core", "", "The first block of every system prompt. It is byte-identical everywhere, so it can be cached.", "",
            block(c.MEMORIA_CORE), ""]
    out += ["## Tenant block", "", "Sent after the system prompt and marked with `cache_control`.", "",
            block(c.TENANT_BLOCK.template), ""]

    for stage in c.CHAIN:
        out += [f"## {TITLES[stage['id']]}", "", settings_line(stage), ""]
        if "systems" in stage:  # assets: one system prompt per asset type
            out += ["### Rules shared by every asset", "", block(c.ASSET_COMMON), ""]
            for asset_type, prompt in c.ASSET_PROMPTS.items():
                out += [f"### Asset: `{asset_type}`", "", "**Stage prompt**", "", block(prompt), "",
                        "**Output schema**", "", schema_table(c.ASSET_SCHEMAS[asset_type]), ""]
            out += ["### User template (all asset types)", "", block(stage["user"].template), ""]
            continue
        out += ["### Stage prompt", "", block(stage_part(stage["system"])), "",
                "### User template", "", block(stage["user"].template), ""]
        if stage.get("finalize"):
            out += ["### Final turn after the tool loop", "",
                    "Sent with `tool_choice: none` and the output schema below.", "",
                    block(stage["finalize"].template), ""]
        if stage.get("schema"):
            out += ["### Output schema", "", schema_table(stage["schema"]), ""]
        else:
            out += ["### Output", "", "Free text (no schema)." if stage["runtime"] == "messages"
                    else "Free text from the Managed Agent session; memory changes are checked with the memory diff.", ""]

    r = c.REVISER
    out += ["## 8b — Reviser", "", "Runs only when the verifier returns `needs_revision`, at most once per asset. "
            "Returns the asset in its original schema.", "",
            "### Stage prompt", "", block(stage_part(r["system"])), "",
            "### User template", "", block(r["user"].template), ""]

    out += ["## Eval prompts", "", "These are used by the eval runner only, never by the agent.", "",
            "### Simulated rep: system", "", block(c.SIMULATED_REP_SYSTEM), "",
            "### Simulated rep: user template", "", block(c.SIMULATED_REP_USER.template), "",
            "### Judge: system", "", block(c.JUDGE_SYSTEM), "",
            "### Judge: user template", "", block(c.JUDGE_USER.template), "",
            "### Judge criteria", "", "| Criterion | Text |", "|---|---|",
            *[f"| `{k}` | {v} |" for k, v in c.JUDGE_CRITERIA.items()], "",
            "### Track test question", "", f"> {c.TRACK_TEST_QUESTION}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
